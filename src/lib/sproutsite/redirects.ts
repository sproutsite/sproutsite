import { existsSync, readFileSync } from 'node:fs';
import { parseDocument } from 'yaml';
import { z } from 'zod';
import { withBase } from './urls.js';

const path = z
    .string()
    .refine(
        (value) =>
            /^\/(?:[A-Za-z0-9._~-]+(?:\/[A-Za-z0-9._~-]+)*\/?)?$/.test(value) &&
            !value
                .split('/')
                .some((segment) => segment === '.' || segment === '..'),
        'expected a root-relative path made of ASCII URL segments, without a query or fragment',
    );
const schema = z.strictObject({
    redirects: z.array(
        z.strictObject({
            from: path,
            to: path,
            status: z.literal(301).default(301),
        }),
    ),
});

export const redirectsFile = 'src/content/redirects.yaml';

export function redirectPathKey(pathname: string): string {
    return '/' + pathname.replace(/^\/|\/$/g, '');
}

export function loadRedirects(file: URL) {
    if (!existsSync(file)) return undefined;
    const document = parseDocument(readFileSync(file, 'utf8'));
    if (document.errors.length)
        throw new Error(
            `${redirectsFile}: ${document.errors.map((error) => error.message).join('; ')}`,
        );
    const result = schema.safeParse(document.toJS());
    if (!result.success)
        throw new Error(
            `${redirectsFile}: ${result.error.issues.map((issue) => `${issue.path.join('.')}: ${issue.message}`).join('; ')}`,
        );

    const sources = new Set<string>();
    for (const { from } of result.data.redirects) {
        if (sources.has(from))
            throw new Error(`${redirectsFile}: duplicate source path ${from}.`);
        sources.add(from);
    }
    const sourcePaths = new Set([...sources].map(redirectPathKey));
    for (const { from, to } of result.data.redirects) {
        if (sourcePaths.has(redirectPathKey(to)))
            throw new Error(
                `${redirectsFile}: ${from} points to redirect source ${to}; use the final page URL.`,
            );
    }
    return result.data.redirects;
}

export type Redirect = NonNullable<ReturnType<typeof loadRedirects>>[number];

export function validateRedirectBase(base: string) {
    if (!path.safeParse(base).success)
        throw new Error(
            `${redirectsFile}: the deployment base must also use plain ASCII URL segments.`,
        );
}

export function renderRedirects(redirects: readonly Redirect[], base: string) {
    const nginx: string[] = [];
    const apache: string[] = [];
    for (const { from, to, status } of redirects) {
        const source = withBase(from, base);
        const target = withBase(to, base);
        // Dots are the only regex metacharacter allowed by the path schema.
        const pattern = source.replaceAll('.', '\\.');
        nginx.push(
            `location = ${source} {\n    absolute_redirect off;\n    return ${status} ${target}$is_args$args;\n}`,
        );
        apache.push(`RedirectMatch ${status} "^${pattern}$" "${target}"`);
    }
    const header =
        '# Generated by Sproutsite from src/content/redirects.yaml.\n';
    return {
        nginx: header + nginx.map((rule) => '\n' + rule + '\n').join(''),
        apache: header + apache.map((rule) => rule + '\n').join(''),
    };
}
